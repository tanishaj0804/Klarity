-- Klarity Sprint 2: Snowflake account setup (stories S2-01 and S2-02).
-- Run once, in a Snowflake worksheet, top to bottom. Safe to re-run.
--
-- BEFORE YOU RUN: generate the keys (python scripts/make_snowflake_keys.py) and replace the
-- three <PUBLIC KEY> placeholders below with the one-line public keys it prints.
--
-- Design:
--   BRONZE  raw copy written by Fivetran (role LOADER)
--   SILVER  clean data written by dbt   (role TRANSFORMER)
--   GOLD    business tables written by dbt, read by the dashboard (REPORTER reads)

USE ROLE ACCOUNTADMIN;

-- 1. Cost protection first -------------------------------------------------------------
CREATE RESOURCE MONITOR IF NOT EXISTS KLARITY_MONITOR
  WITH CREDIT_QUOTA = 30            -- adjust to your trial credits; this is a safety stop
  FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 50 PERCENT DO NOTIFY
           ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

-- 2. Warehouses (extra small, suspend after 60 seconds idle) ----------------------------
USE ROLE SYSADMIN;
CREATE WAREHOUSE IF NOT EXISTS FIVETRAN_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE ROLE ACCOUNTADMIN;
ALTER WAREHOUSE FIVETRAN_WH SET RESOURCE_MONITOR = KLARITY_MONITOR;
ALTER WAREHOUSE TRANSFORM_WH SET RESOURCE_MONITOR = KLARITY_MONITOR;

-- 3. Databases and schemas ---------------------------------------------------------------
USE ROLE SYSADMIN;
CREATE DATABASE IF NOT EXISTS BRONZE;
CREATE DATABASE IF NOT EXISTS SILVER;
CREATE DATABASE IF NOT EXISTS GOLD;
CREATE SCHEMA IF NOT EXISTS SILVER.CORE;
CREATE SCHEMA IF NOT EXISTS GOLD.MART;

-- 4. Roles ---------------------------------------------------------------------------------
USE ROLE USERADMIN;
CREATE ROLE IF NOT EXISTS LOADER;        -- Fivetran: writes BRONZE only
CREATE ROLE IF NOT EXISTS TRANSFORMER;   -- dbt: reads BRONZE, writes SILVER and GOLD
CREATE ROLE IF NOT EXISTS REPORTER;      -- dashboard: reads GOLD only
GRANT ROLE LOADER, TRANSFORMER, REPORTER TO ROLE SYSADMIN;

-- 5. Grants ---------------------------------------------------------------------------------
USE ROLE SECURITYADMIN;
GRANT USAGE ON WAREHOUSE FIVETRAN_WH TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE REPORTER;

-- LOADER: Fivetran creates its own schemas inside BRONZE
GRANT USAGE, MONITOR, CREATE SCHEMA ON DATABASE BRONZE TO ROLE LOADER;

-- TRANSFORMER: read everything Fivetran creates (now and in future)
GRANT USAGE ON DATABASE BRONZE TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE BRONZE TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE BRONZE TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE BRONZE TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN DATABASE BRONZE TO ROLE TRANSFORMER;

-- TRANSFORMER: owns what dbt builds in SILVER.CORE and GOLD.MART
GRANT USAGE ON DATABASE SILVER TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA SILVER.CORE TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE GOLD TO ROLE TRANSFORMER;
GRANT ALL PRIVILEGES ON SCHEMA GOLD.MART TO ROLE TRANSFORMER;

-- REPORTER: read GOLD only
GRANT USAGE ON DATABASE GOLD TO ROLE REPORTER;
GRANT USAGE ON SCHEMA GOLD.MART TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES IN SCHEMA GOLD.MART TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GOLD.MART TO ROLE REPORTER;
GRANT SELECT ON ALL VIEWS IN SCHEMA GOLD.MART TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA GOLD.MART TO ROLE REPORTER;

-- 6. Service users with key-pair login (no passwords) -------------------------------------
-- Replace each <PUBLIC KEY> with the one-line key printed by scripts/make_snowflake_keys.py.
USE ROLE USERADMIN;
CREATE USER IF NOT EXISTS FIVETRAN_USER TYPE = SERVICE DEFAULT_ROLE = LOADER
  DEFAULT_WAREHOUSE = FIVETRAN_WH COMMENT = 'Fivetran destination user';
CREATE USER IF NOT EXISTS DBT_USER TYPE = SERVICE DEFAULT_ROLE = TRANSFORMER
  DEFAULT_WAREHOUSE = TRANSFORM_WH COMMENT = 'dbt and loaders';
CREATE USER IF NOT EXISTS APP_USER TYPE = SERVICE DEFAULT_ROLE = REPORTER
  DEFAULT_WAREHOUSE = TRANSFORM_WH COMMENT = 'Dashboard (read GOLD only)';

ALTER USER FIVETRAN_USER SET RSA_PUBLIC_KEY = '<PUBLIC KEY FOR FIVETRAN_USER>';
ALTER USER DBT_USER      SET RSA_PUBLIC_KEY = '<PUBLIC KEY FOR DBT_USER>';
ALTER USER APP_USER      SET RSA_PUBLIC_KEY = '<PUBLIC KEY FOR APP_USER>';

USE ROLE SECURITYADMIN;
GRANT ROLE LOADER TO USER FIVETRAN_USER;
GRANT ROLE TRANSFORMER TO USER DBT_USER;
GRANT ROLE REPORTER TO USER APP_USER;

